#!/usr/bin/env python3
"""Generate build/finte_version.h from base.h and git HEAD."""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "src" / "include" / "finte" / "base.h"
DEFAULT = "0.0.0"


def base_version() -> str:
    try:
        text = BASE.read_text(encoding="utf-8")
    except OSError:
        return DEFAULT
    values = []
    for part in ("MAJOR", "MINOR", "PATCH"):
        match = re.search(rf"#define\s+FINTE_VERSION_{part}\s+(\d+)", text)
        if not match:
            return DEFAULT
        values.append(match.group(1))
    return ".".join(values)


def commit_hash() -> str:
    try:
        result = subprocess.run(
            ["git", "-C", str(ROOT), "rev-parse", "--short=7", "HEAD"],
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        return ""
    if result.returncode != 0:
        return ""
    value = result.stdout.strip()
    return value if re.fullmatch(r"[0-9a-f]{7,40}", value) else ""


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: gen_version.py OUTPUT", file=sys.stderr)
        return 2
    version = base_version()
    commit = commit_hash()
    if commit:
        version = f"{version}-{commit}"
    header = (
        "/* Generated by tools/gen_version.py. Do not edit. */\n"
        "#ifndef FINTE_VERSION_H\n"
        "#define FINTE_VERSION_H\n"
        f'#define FINTE_VERSION_STRING "{version}"\n'
        "#endif\n"
    )
    output = Path(sys.argv[1])
    output.parent.mkdir(parents=True, exist_ok=True)
    old = output.read_text(encoding="utf-8") if output.exists() else ""
    if old != header:
        output.write_text(header, encoding="utf-8", newline="")
    print(f"version {version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
