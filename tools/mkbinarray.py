#!/usr/bin/env python3
"""Convert a binary file into a C byte array for the kernel."""
import sys


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: mkbinarray.py INPUT OUTPUT SYMBOL", file=sys.stderr)
        return 1
    src, dst, symbol = sys.argv[1:4]
    data = open(src, "rb").read()
    with open(dst, "w", encoding="ascii") as f:
        f.write("/* generated by tools/mkbinarray.py */\n")
        f.write(f"const unsigned char {symbol}[] = {{\n")
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            f.write("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",\n")
        f.write("};\n")
        f.write(f"const unsigned int {symbol}_len = {len(data)}u;\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
